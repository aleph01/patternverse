import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const web = fileURLToPath(new URL('../', import.meta.url));
async function bundleScript(entry, name) {
  const result = await build({
    configFile: false,
    publicDir: false,
    logLevel: 'warn',
    build: {
      write: false,
      minify: true,
      lib: { entry: entry, name, formats: ['iife'] },
    },
  });
  const output = Array.isArray(result) ? result.flatMap((item) => item.output) : result.output;
  const chunk = output.find((item) => item.type === 'chunk' && item.isEntry);
  if (!chunk) throw new Error('The Plot example did not produce a script.');

  // Keep dependency notices with the self-contained HTML distributed to readers.
  const packages = new Set();
  const notices = new Map();
  for (const module of Object.keys(chunk.modules)) {
    if (!module.includes('/node_modules/')) continue;
    let directory = dirname(module);
    while (directory.includes('/node_modules/')) {
      if (packages.has(directory)) break;
      try {
        const metadata = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
        packages.add(directory);
        let license;
        for (const filename of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
          try {
            license = await readFile(resolve(directory, filename), 'utf8');
            break;
          } catch {
            /* Try another conventional name. */
          }
        }
        if (!license) throw new Error(`Missing license for ${metadata.name}`);
        notices.set(`${metadata.name}@${metadata.version}`, license);
        break;
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
        directory = dirname(directory);
      }
    }
  }
  const licenses = [...notices]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, license]) => `${name}\n${license}`)
    .join('\n\n');

  return { code: chunk.code, licenses, notices: notices.size };
}

const source = resolve(web, 'src/lib/article-widgets/dataviz/sort-order');
const destination = resolve(web, '../../content/assets/widgets/dataviz-sort-order.html');
const bundle = await bundleScript(`${source}.ts`, 'SortOrderExample');
const { code, licenses } = bundle;
const { ticketCounts } = await import('../src/lib/article-widgets/dataviz/sort-order-data.ts');
const rows = ticketCounts
  .map(({ category, tickets }) => `<tr><th scope="row">${category}</th><td>${tickets}</td></tr>`)
  .join('\n');
const template = await readFile(`${source}.html`, 'utf8');
const html = template
  .replace('<!-- DATA_ROWS -->', rows)
  .replace(
    '<!-- PLOT_SCRIPT -->',
    () =>
      `<!-- Generated by pnpm build:dataviz-widgets. Edit the source template and TypeScript.\n${licenses.replaceAll('--', '—')}\n-->\n<script>${code.replace(/<\/script/gi, '<\\/script')}</script>`,
  );
if (html.length > 512_000)
  throw new Error(`Widget exceeds its 512 KB limit: ${html.length} characters.`);
await writeFile(destination, html);
console.log(
  `Built ${destination} (${Buffer.byteLength(html)} bytes, ${bundle.notices} dependency notices).`,
);

const { lessonManifest } = await import('../src/lib/article-widgets/dataviz/lesson-manifest.ts');
const { tableForLesson } = await import('../src/lib/article-widgets/dataviz/lesson-data.ts');
const { expansionManifest } =
  await import('../src/lib/article-widgets/dataviz/expansion-manifest.ts');
const { expansionTable } = await import('../src/lib/article-widgets/dataviz/expansion-data.ts');
const lessonTemplate = await readFile(
  resolve(web, 'src/lib/article-widgets/dataviz/lesson.html'),
  'utf8',
);
const escape = (value) =>
  String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
for (const group of [
  { manifest: lessonManifest, table: tableForLesson, entry: 'lesson-explorer.ts' },
  { manifest: expansionManifest, table: expansionTable, entry: 'expansion-explorer.ts' },
]) {
  const shared = await bundleScript(
    resolve(web, 'src/lib/article-widgets/dataviz', group.entry),
    'VisualLesson',
  );
  for (const lesson of group.manifest) {
    const table = group.table(lesson.id);
    const replacements = {
      TITLE: escape(lesson.title),
      LESSON_ID: lesson.id,
      CONTEXT: escape(lesson.context),
      CONTROL: escape(lesson.control),
      FALLBACK: escape(lesson.fallback),
      MODES: lesson.modes
        .map(
          ([value, label], index) =>
            `<label><input type="radio" name="mode" value="${escape(value)}"${index === 0 ? ' checked' : ''} /> ${escape(label)}</label>`,
        )
        .join('\n'),
      EXTRA:
        'extra' in lesson
          ? `<label class="extra"><input type="checkbox" id="grayscale" /> ${escape(lesson.extra)}</label>`
          : (lesson.controls ?? [])
              .map((control) => {
                const inputId = `control-${control.key}`;
                if (control.type === 'select')
                  return `<label class="extra">${escape(control.label)}<select id="${inputId}" aria-label="${escape(control.label)}">${control.options.map(([value, label]) => `<option value="${escape(value)}"${String(control.value) === value ? ' selected' : ''}>${escape(label)}</option>`).join('')}</select></label>`;
                return `<label class="extra range-control" for="${inputId}">${escape(control.label)}<input id="${inputId}" type="range" aria-label="${escape(control.label)}" min="${control.min}" max="${control.max}" step="${control.step}" value="${control.value}" /><output id="value-${control.key}" for="${inputId}">${control.value}</output></label>`;
              })
              .join('\n'),
      TABLE_HEAD: table.columns.map((column) => `<th scope="col">${escape(column)}</th>`).join(''),
      TABLE_ROWS: table.rows
        .map(
          (row) =>
            `<tr>${row.map((value, index) => (index === 0 ? `<th scope="row">${escape(value)}</th>` : `<td>${escape(value)}</td>`)).join('')}</tr>`,
        )
        .join('\n'),
      PLOT_SCRIPT: `<!-- Generated by pnpm build:dataviz-widgets.\n${shared.licenses.replaceAll('--', '—')}\n-->\n<script>${shared.code.replace(/<\/script/gi, '<\\/script')}</script>`,
    };
    const sourceTemplate =
      group.entry === 'expansion-explorer.ts'
        ? lessonTemplate.replace(
            '</style>',
            '.range-control { display: flex; flex-wrap: wrap; cursor: default; } .range-control input { flex: 1; min-width: 80px; max-width: 260px; min-height: 30px; } output { min-width: 2ch; font-variant-numeric: tabular-nums; } select { font: inherit; max-width: 100%; background: white; color: #252822; padding: 5px; } </style>',
          )
        : lessonTemplate;
    const html = sourceTemplate.replace(/<!-- ([A-Z_]+) -->/g, (_, name) => {
      if (!(name in replacements)) throw new Error(`Unknown template field ${name}`);
      return replacements[name];
    });
    if (html.length > 512_000) throw new Error(`Widget ${lesson.id} exceeds the 512 KB bound.`);
    const destination = resolve(web, `../../content/assets/widgets/dataviz-${lesson.id}.html`);
    await writeFile(destination, html);
    console.log(`Built dataviz-${lesson.id}.html (${Buffer.byteLength(html)} bytes).`);
  }
}
