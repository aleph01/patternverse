export const originalRecords = domains.flatMap((domain) =>
  domain.entries.map(([id, family_name, subjects, statement, judgment, clarification]) => ({
    id,
    statement,
    domain: domain.id,
    domain_name: domain.title,
    family_name,
    subjects,
    judgment,
    judgment_name: judgments.find((item) => item.id === judgment).title,
    recognition_cues: subjects,
    clarification,
    meaning_boundary: domain.boundary,
  })),
);

// The old IDs still identify exactly the original statements. New examples have
// explicit suffixes; subfamily_id is a separate grouping link, never a selectable verdict.
export const subfamilies = originalRecords.map((record) => ({
  id: record.id,
  title: record.family_name,
  domain: record.domain,
  clarification: record.clarification,
  meaning_boundary: record.meaning_boundary,
}));

export const records = originalRecords.flatMap((record) => [
  { ...record, subfamily_id: record.id, scope: 'unspecified' },
  ...examples[record.id].map(([suffix, statement, judgment, scope, subjects, options]) => ({
    ...record,
    id: `${record.id}-${suffix}`,
    statement,
    subfamily_id: record.id,
    scope,
    judgment,
    judgment_name: judgments.find((item) => item.id === judgment).title,
    subjects,
    recognition_cues: subjects,
    clarification: options?.clarification ?? record.clarification,
  })),
]);

export const library = {
  version: '0.2',
  description:
    'Editorial candidate taxonomy of aspects of oneself regarded as unacceptable. Not a diagnosis, ethical verdict or claim that a person holds any listed judgment.',
  domains: domains.map(({ entries, ...domain }) => ({
    ...domain,
    ids: records.filter((record) => record.domain === domain.id).map((record) => record.id),
    subfamily_ids: entries.map(([id]) => id),
  })),
  subfamilies,
  judgments,
  records,
};
